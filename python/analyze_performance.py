#!/usr/bin/env python3
"""Summarize Octree navigation benchmark CSV files.

Input rows are generated by build/octree_performance_benchmark through
scripts/run_performance_benchmark.sh. The script prints mean metrics by mode,
writes a JSON report, and optionally saves simple bar charts when matplotlib is
available.
"""

from __future__ import annotations

import argparse
import csv
import json
from collections import defaultdict
from pathlib import Path
from statistics import mean


NUMERIC_FIELDS = [
    "source_points",
    "used_points",
    "parse_ms",
    "build_ms",
    "plan_ms",
    "total_ms",
    "node_count",
    "leaf_count",
    "estimated_node_memory_kb",
    "rss_kb_after",
    "peak_rss_kb",
    "expanded_nodes",
    "waypoints",
    "path_cost",
]


