def load_rows(path: Path) -> list[dict[str, object]]:
    rows: list[dict[str, object]] = []
    with path.open(newline="") as handle:
        reader = csv.DictReader(handle)
        for row in reader:
            converted: dict[str, object] = dict(row)
            for field in NUMERIC_FIELDS:
                if field in row and row[field] != "":
                    converted[field] = float(row[field])
            converted["path_success"] = row.get("path_success") in {"1", "true", "True"}
            converted["frame"] = int(row.get("frame", 0))
            rows.append(converted)
    return rows


def percentage_reduction(baseline: float, current: float) -> float | None:
    if baseline == 0:
        return None
    return (baseline - current) / baseline * 100.0


def safe_ratio(numerator: float, denominator: float) -> float | None:
    if denominator == 0:
        return None
    return numerator / denominator


def summarize(
    rows: list[dict[str, object]],
    raw_point_bytes: float,
    point_graph_bytes: float,
) -> dict[str, object]:
    grouped: dict[str, list[dict[str, object]]] = defaultdict(list)
    for row in rows:
        grouped[str(row["mode"])].append(row)

    summary: dict[str, object] = {
        "modes": {},
        "assumptions": {
            "raw_point_bytes": raw_point_bytes,
            "point_graph_bytes": point_graph_bytes,
        },
    }
    for mode, items in grouped.items():
        mode_summary: dict[str, object] = {
            "frames": len(items),
            "success_rate": mean(1.0 if item["path_success"] else 0.0 for item in items),
        }
        for field in NUMERIC_FIELDS:
            values = [float(item[field]) for item in items if field in item]
            if values:
                mode_summary[f"mean_{field}"] = mean(values)
                mode_summary[f"min_{field}"] = min(values)
                mode_summary[f"max_{field}"] = max(values)
        used_points = float(mode_summary.get("mean_used_points", 0.0))
        octree_memory_kb = float(mode_summary.get("mean_estimated_node_memory_kb", 0.0))
        raw_cloud_memory_kb = used_points * raw_point_bytes / 1024.0
        point_graph_memory_kb = used_points * point_graph_bytes / 1024.0
        mode_summary["estimated_raw_pointcloud_memory_kb"] = raw_cloud_memory_kb
        mode_summary["estimated_point_graph_memory_kb"] = point_graph_memory_kb
        mode_summary["octree_vs_raw_pointcloud_memory_reduction_percent"] = percentage_reduction(
            raw_cloud_memory_kb,
            octree_memory_kb,
        )
        mode_summary["octree_vs_point_graph_memory_reduction_percent"] = percentage_reduction(
            point_graph_memory_kb,
            octree_memory_kb,
        )
        mean_plan_ms = float(mode_summary.get("mean_plan_ms", 0.0))
        mean_total_ms = float(mode_summary.get("mean_total_ms", 0.0))
        mean_expanded = float(mode_summary.get("mean_expanded_nodes", 0.0))
        mode_summary["planning_hz"] = safe_ratio(1000.0, mean_plan_ms)
        mode_summary["end_to_end_hz"] = safe_ratio(1000.0, mean_total_ms)
        mode_summary["expanded_nodes_per_second"] = (
            safe_ratio(mean_expanded * 1000.0, mean_plan_ms)
        )
        summary["modes"][mode] = mode_summary

    semantic = summary["modes"].get("semantic_octree_astar")
    rf = summary["modes"].get("rf_octree_astar")
    if semantic and rf:
        comparison = {}
        for field in ["total_ms", "build_ms", "plan_ms", "expanded_nodes", "waypoints", "path_cost"]:
            s = semantic.get(f"mean_{field}")
            r = rf.get(f"mean_{field}")
            if s is not None and r is not None:
                comparison[f"rf_minus_semantic_mean_{field}"] = r - s
                improvement = percentage_reduction(float(s), float(r))
                if improvement is not None:
                    comparison[f"rf_vs_semantic_{field}_improvement_percent"] = improvement
                if s != 0:
                    comparison[f"rf_vs_semantic_{field}_ratio"] = r / s
                    comparison[f"semantic_vs_rf_{field}_speedup"] = s / r if r != 0 else None
        for field in ["planning_hz", "end_to_end_hz", "expanded_nodes_per_second"]:
            s = semantic.get(field)
            r = rf.get(field)
            if s is not None and r is not None:
                comparison[f"rf_minus_semantic_{field}"] = r - s
                comparison[f"rf_vs_semantic_{field}_gain_percent"] = (
                    (r - s) / s * 100.0 if s != 0 else None
                )
                comparison[f"rf_vs_semantic_{field}_ratio"] = r / s if s != 0 else None
        comparison["total_latency_saved_ms"] = (
            float(semantic.get("mean_total_ms", 0.0)) - float(rf.get("mean_total_ms", 0.0))
        )
        comparison["plan_latency_saved_ms"] = (
            float(semantic.get("mean_plan_ms", 0.0)) - float(rf.get("mean_plan_ms", 0.0))
        )
        comparison["expanded_nodes_saved"] = (
            float(semantic.get("mean_expanded_nodes", 0.0)) -
            float(rf.get("mean_expanded_nodes", 0.0))
        )
        comparison["build_overhead_ms"] = (
            float(rf.get("mean_build_ms", 0.0)) - float(semantic.get("mean_build_ms", 0.0))
        )
        summary["comparison"] = comparison

    return summary


def fmt_number(value: object, digits: int = 2) -> str:
    if value is None:
        return "N/A"
    return f"{float(value):.{digits}f}"


def fmt_percent(value: object) -> str:
    if value is None:
        return "N/A"
    return f"{float(value):+.2f}%"


def fmt_compact_ms(value: object) -> str:
    if value is None:
        return "N/A"
    value = float(value)
    if abs(value) >= 1000.0:
        return f"{value / 1000.0:.2f} s"
    return f"{value:.1f} ms"


def improvement_text(value: object) -> str:
    if value is None:
        return "N/A"
    return f"{float(value):+.1f}%"


def fmt_speedup(value: object) -> str:
    if value is None:
        return "N/A"
    return f"{float(value):.2f}x"


def build_markdown_table(summary: dict[str, object]) -> str:
    modes = summary["modes"]
    lines = [
        "# Octree Performance Summary",
        "",
        "## Mode Metrics",
        "",
        "| Mode | Total ms | Build ms | Plan ms | Expanded Nodes | Planning Hz | Path Cost |",
        "|---|---:|---:|---:|---:|---:|---:|",
    ]
    for mode, data in modes.items():
        lines.append(
            "| "
            f"{mode} | "
            f"{fmt_number(data.get('mean_total_ms'))} | "
            f"{fmt_number(data.get('mean_build_ms'))} | "
            f"{fmt_number(data.get('mean_plan_ms'))} | "
            f"{fmt_number(data.get('mean_expanded_nodes'), 0)} | "
            f"{fmt_number(data.get('planning_hz'), 3)} | "
            f"{fmt_number(data.get('mean_path_cost'))} |"
        )

    comparison = summary.get("comparison", {})
    lines.extend([
        "",
        "## RF Improvement Over Semantic/Baseline Octree",
        "",
        "| Metric | Baseline Mean | RF Mean | Change |",
        "|---|---:|---:|---:|",
    ])
    metric_rows = [
        ("Total time", "total_ms", "ms", 2),
        ("Build time", "build_ms", "ms", 2),
        ("A* plan time", "plan_ms", "ms", 2),
        ("Expanded nodes", "expanded_nodes", "nodes", 0),
        ("Path cost", "path_cost", "cost", 2),
    ]
    semantic = modes.get("semantic_octree_astar", {})
    rf = modes.get("rf_octree_astar", {})
    for label, field, unit, digits in metric_rows:
        baseline = semantic.get(f"mean_{field}")
        current = rf.get(f"mean_{field}")
        improvement = comparison.get(f"rf_vs_semantic_{field}_improvement_percent")
        lines.append(
            "| "
            f"{label} | "
            f"{fmt_number(baseline, digits)} {unit} | "
            f"{fmt_number(current, digits)} {unit} | "
            f"{fmt_percent(improvement)} |"
        )
    lines.extend([
        "",
        "## Derived Poster Metrics",
        "",
        "| Metric | Value | Meaning |",
        "|---|---:|---|",
        f"| Total speedup | {fmt_speedup(comparison.get('semantic_vs_rf_total_ms_speedup'))} | Baseline total time / RF total time |",
        f"| A* planning speedup | {fmt_speedup(comparison.get('semantic_vs_rf_plan_ms_speedup'))} | Baseline A* time / RF A* time |",
        f"| Total latency saved | {fmt_number(comparison.get('total_latency_saved_ms'))} ms | End-to-end time reduced by RF Octree |",
        f"| A* latency saved | {fmt_number(comparison.get('plan_latency_saved_ms'))} ms | Planner time reduced by RF semantics |",
        f"| Expanded nodes saved | {fmt_number(comparison.get('expanded_nodes_saved'), 0)} nodes | Search-space reduction |",
        f"| Build overhead | {fmt_number(comparison.get('build_overhead_ms'))} ms | Extra RF prediction cost during Octree build |",
    ])
    return "\n".join(lines) + "\n"


def write_markdown_table(summary: dict[str, object], output: Path) -> None:
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(build_markdown_table(summary), encoding="utf-8")
    print(f"Saved table: {output}")


def print_summary(summary: dict[str, object]) -> None:
    print("Performance summary")
    print("===================")
    for mode, data in summary["modes"].items():
        print(f"\n{mode}")
        print(f"  frames: {data['frames']}")
        for field in ["total_ms", "build_ms", "plan_ms", "expanded_nodes", "path_cost"]:
            key = f"mean_{field}"
            if key in data:
                print(f"  {key}: {data[key]:.3f}")
        if data.get("planning_hz") is not None:
            print(f"  planning_hz: {data['planning_hz']:.3f}")
    if "comparison" in summary:
        print("\nRF - semantic improvement")
        for field in ["total_ms", "build_ms", "plan_ms", "expanded_nodes", "path_cost"]:
            key = f"rf_vs_semantic_{field}_improvement_percent"
            if key in summary["comparison"]:
                print(f"  {field}: {summary['comparison'][key]:+.2f}%")
        print(f"  total_speedup: {fmt_speedup(summary['comparison'].get('semantic_vs_rf_total_ms_speedup'))}")
        print(f"  plan_speedup: {fmt_speedup(summary['comparison'].get('semantic_vs_rf_plan_ms_speedup'))}")
        print(f"  total_latency_saved_ms: {summary['comparison'].get('total_latency_saved_ms', 0.0):.3f}")
        print(f"  expanded_nodes_saved: {summary['comparison'].get('expanded_nodes_saved', 0.0):.0f}")


def format_bar_value(metric: str, value: float) -> str:
    if "expanded_nodes" in metric:
        return f"{value:.0f}"
    if metric.endswith("_ms"):
        return f"{value:.1f} ms"
    if metric.endswith("_kb"):
        return f"{value:.0f} KB"
    return f"{value:.2f}"


def annotate_bars(ax, bars, metric: str) -> None:
    values = [bar.get_height() for bar in bars]
    max_value = max(values) if values else 0.0
    y_offset = max(max_value * 0.025, 0.5)
    for bar in bars:
        value = bar.get_height()
        ax.text(
            bar.get_x() + bar.get_width() / 2.0,
            value + y_offset,
            format_bar_value(metric, value),
            ha="center",
            va="bottom",
            fontsize=8,
        )
    if max_value > 0:
        ax.set_ylim(top=max_value * 1.18)


def maybe_plot(summary: dict[str, object], output: Path) -> None:
    try:
        import matplotlib.pyplot as plt
    except Exception:
        print("matplotlib not available; skipped plot generation")
        return

    modes = list(summary["modes"].keys())
    metrics = ["mean_build_ms", "mean_plan_ms", "mean_total_ms", "mean_expanded_nodes"]
    titles = ["Build ms", "Plan ms", "Total ms", "Expanded nodes"]

    fig, axes = plt.subplots(1, len(metrics), figsize=(16, 4))
    for ax, metric, title in zip(axes, metrics, titles):
        values = [summary["modes"][mode].get(metric, 0.0) for mode in modes]
        bars = ax.bar(modes, values, color=["#3b82f6", "#ef4444"][: len(modes)])
        annotate_bars(ax, bars, metric)
        ax.set_title(title)
        ax.tick_params(axis="x", rotation=25)
    fig.tight_layout()
    output.parent.mkdir(parents=True, exist_ok=True)
    fig.savefig(output, dpi=160)
    print(f"Saved plot: {output}")


