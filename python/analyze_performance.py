def maybe_plot_poster_chart(summary: dict[str, object], output: Path) -> None:
    try:
        import matplotlib.pyplot as plt
        import numpy as np
    except Exception:
        print("matplotlib not available; skipped poster chart generation")
        return

    modes = summary["modes"]
    semantic = modes.get("semantic_octree_astar", {})
    rf = modes.get("rf_octree_astar", {})

    fig, metrics_ax = plt.subplots(figsize=(15, 8.2), dpi=180)
    fig.patch.set_facecolor("#f8fafc")
    metrics_ax.set_facecolor("#ffffff")

    labels = ["Total\nTime", "A* Plan\nTime", "Expanded\nNodes", "Path\nCost"]
    baseline_values = [
        float(semantic.get("mean_total_ms", 0.0)) / 1000.0,
        float(semantic.get("mean_plan_ms", 0.0)) / 1000.0,
        float(semantic.get("mean_expanded_nodes", 0.0)) / 1000.0,
        float(semantic.get("mean_path_cost", 0.0)),
    ]
    rf_values = [
        float(rf.get("mean_total_ms", 0.0)) / 1000.0,
        float(rf.get("mean_plan_ms", 0.0)) / 1000.0,
        float(rf.get("mean_expanded_nodes", 0.0)) / 1000.0,
        float(rf.get("mean_path_cost", 0.0)),
    ]
    units = ["s", "s", "k nodes", "cost"]
    x = np.arange(len(labels))
    width = 0.36
    bars_a = metrics_ax.bar(
        x - width / 2,
        baseline_values,
        width,
        label="Semantic Octree",
        color="#94a3b8",
    )
    bars_b = metrics_ax.bar(x + width / 2, rf_values, width, label="RF Octree", color="#06b6d4")
    metrics_ax.set_title("Runtime / Search / Memory Comparison", fontsize=24, weight="bold", pad=24)
    metrics_ax.text(
        0.5,
        1.01,
        "Lower bars are better. Path cost includes distance, risk, stair, and vertical-movement penalties.",
        ha="center",
        va="bottom",
        fontsize=13.5,
        color="#475569",
        transform=metrics_ax.transAxes,
    )
    metrics_ax.set_xticks(x, labels, fontsize=17)
    metrics_ax.tick_params(axis="y", labelsize=13)
    metrics_ax.grid(axis="y", color="#cbd5e1", alpha=0.65)
    metrics_ax.set_axisbelow(True)
    metrics_ax.legend(frameon=False, fontsize=14, loc="upper right")
    for bars in [bars_a, bars_b]:
        for idx, bar in enumerate(bars):
            height = bar.get_height()
            metrics_ax.text(
                bar.get_x() + bar.get_width() / 2.0,
                height + max(max(baseline_values + rf_values) * 0.018, 0.02),
                f"{height:.2f} {units[idx]}",
                ha="center",
                va="bottom",
                fontsize=12,
                color="#0f172a",
            )
    metrics_ax.set_ylim(top=max(baseline_values + rf_values) * 1.24 if baseline_values else 1.0)
    metrics_ax.set_ylabel("Seconds / Thousand Nodes / Cost", fontsize=14, color="#334155")
    fig.tight_layout(pad=2.0)

    output.parent.mkdir(parents=True, exist_ok=True)
    fig.savefig(output, bbox_inches="tight")
    print(f"Saved poster chart: {output}")


