def main() -> int:
    args = parse_args()
    input_path = Path(args.input)
    if not input_path.exists():
        raise FileNotFoundError(f"Benchmark CSV not found: {input_path}")

    rows = load_rows(input_path)
    if not rows:
        raise RuntimeError(f"No rows found in {input_path}")

    summary = summarize(rows, args.raw_point_bytes, args.point_graph_bytes)
    print_summary(summary)

    output_json = Path(args.output_json)
    output_json.parent.mkdir(parents=True, exist_ok=True)
    output_json.write_text(json.dumps(summary, indent=2), encoding="utf-8")
    print(f"Saved JSON: {output_json}")

    write_markdown_table(summary, Path(args.output_table))
    maybe_plot(summary, Path(args.plot))
    maybe_plot_table(summary, Path(args.table_plot))
    maybe_plot_poster_chart(summary, Path(args.poster_chart))
    maybe_plot_poster_table(summary, Path(args.poster_table))
    return 0


